const assert = require("node:assert/strict");
require("./catalog.js"); require("./planner.js");
const catalog = globalThis.BuildCatalog;
const { initialState, buildPlan, shellQuote } = globalThis.BuildPlanner;
let state = initialState(catalog), plan = buildPlan(catalog, state);
assert.equal(plan.reasons.length, 0);
assert.equal(plan.commands.length, 3);
assert.match(plan.commands[0], /ROBOFRAME_PRODUCT=demo_robot/);
assert.match(plan.buildDirectory, /\/demo_robot\//);
const invalidProduct = JSON.parse(JSON.stringify(catalog));
invalidProduct.scenarios[0].product = "../robot";
assert.throws(() => buildPlan(invalidProduct, state), /产品目录/);
assert.match(plan.commands[0], /ROBOFRAME_ODOM_SOURCE=SOURCE/);
assert.doesNotMatch(plan.commands[0], /BUILD_DEMO/);
state.tests = false;
assert.equal(buildPlan(catalog, state).commands.length, 2);
state.sources.odom = "PACKAGE";
plan = buildPlan(catalog, state);
assert.equal(plan.reasons.length, 0);
assert.match(plan.commands[0], /ROBOFRAME_ODOM_SOURCE=PACKAGE/);
assert.match(plan.commands[0], /ROBOFRAME_MAP_UPDATER_SOURCE=SOURCE/);
assert.match(plan.commands[0], /ROBOFRAME_SDK_SOURCE=PACKAGE/);
for (const id of Object.keys(state.sources)) state.sources[id] = "PACKAGE";
assert.match(buildPlan(catalog, state).commands[0], /USE_INSTALLED_COMPONENTS=ON/);
assert.equal(shellQuote("a'b"), "'a'\"'\"'b'");
for (const prefix of ["relative/path", "/one;/two", "/one\n/two"]) {
  state.packagePrefix = prefix; assert.equal(buildPlan(catalog, state).commands.length, 0);
}
state = initialState(catalog); state.platform = "linux-aarch64";
assert.equal(buildPlan(catalog, state).commands.length, 0);
state = initialState(catalog); state.sources.odom = "AUTO";
assert.throws(() => buildPlan(catalog, state), /无效/);
const extended = JSON.parse(JSON.stringify(catalog));
extended.components.push({ id: "qr-detector", implemented: false });
extended.scenarios.push({ id: "qr", product: "qr_robot", components: ["qr-detector"], defaults: ["PACKAGE"], buildReady: false });
assert.equal(buildPlan(extended, initialState(extended, "qr")).commands.length, 0);
console.log("PASS: capability catalog, source/package/mixed commands and ARM preview guard");
